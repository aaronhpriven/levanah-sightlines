  let cur = LANGS[0];
  const listeners = [];

  function findLang(code) {
    if (!code) return null;
    const base = String(code).toLowerCase().split("-")[0];
    return LANGS.find(l => l.code === base) || null;
  }

  function t(key, vars) {
    let s = (DICT[cur.code] && DICT[cur.code][key]) ?? DICT.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        s = s.replaceAll(`{${k}}`, String(v));
      }
    }
    return s;
  }

  function month(name) {
    return (MONTHS[cur.code] && MONTHS[cur.code][name]) || name;
  }

  function hebDate(str) {
    // e.g. "12 Kislev" -> "12 כסלו"
    const m = String(str || "").match(/^(\d+)\s+(.+)$/);
    return m ? `${m[1]} ${month(m[2])}` : str;
  }

  function compass(dir) {
    return (COMPASS[cur.code] && COMPASS[cur.code][dir]) || dir;
  }

  function tag(raw) {
    if (raw === "Motzaei Shabbos") return t("tagMotzaeiShabbos");
    if (raw === "Motzaei YK") return t("tagMotzaeiYK");
    if (raw === "Motzaei 9 Av") return t("tagMotzaei9Av");
    return raw;
  }

  function applyDom() {
    document.documentElement.lang = cur.code;
    document.documentElement.dir = cur.dir;
    document.querySelectorAll("[data-i18n]").forEach(el => {
      el.textContent = t(el.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-html]").forEach(el => {
      el.innerHTML = t(el.dataset.i18nHtml);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
      el.placeholder = t(el.dataset.i18nPlaceholder);
    });
    const sel = document.getElementById("langSelect");
    if (sel) sel.value = cur.code;
  }

  function setLang(code, persist = true) {
    const found = findLang(code);
    if (!found) return;
    cur = found;
    if (persist) {
      try { localStorage.setItem("levanah_lang", cur.code); } catch { /* ignore */ }
    }
    applyDom();
    listeners.forEach(fn => { try { fn(cur); } catch (e) { console.error(e); } });
  }

  function init(params) {
    let pick = findLang(params && params.get("lang"));
    if (!pick) {
      try { pick = findLang(localStorage.getItem("levanah_lang")); } catch { /* ignore */ }
    }
    if (!pick && typeof navigator !== "undefined") {
      const langs = navigator.languages || [navigator.language];
      for (const l of langs) { pick = findLang(l); if (pick) break; }
    }
    cur = pick || LANGS[0];
    applyDom();
  }

  function onChange(fn) { listeners.push(fn); }

  return {
    LANGS,
    get code() { return cur.code; },
    get dir() { return cur.dir; },
    get locale() { return cur.locale; },
    init, setLang, applyDom, onChange,
    t, month, hebDate, compass, tag,
  };
